def mask_email(email):
    """h****s@gmail.com - the page is public, the owner's address isn't."""
    if not email or "@" not in email:
        return email or ""
    user, _, domain = email.partition("@")
    if len(user) <= 2:
        return f"{user[0]}*@{domain}"
    return f"{user[0]}{'*' * (len(user) - 2)}{user[-1]}@{domain}"


def drive_status(gdrive):
    """A cheap liveness check against the Drive API. Takes the GoogleDrive
    instance explicitly so it can be called both from a family account's
    request (g.gdrive) and from the admin panel (one per pool account,
    outside any /u/<user_id>/ request context)."""
    try:
        about = (
            gdrive.drive_instance.about()
            .get(fields="user(displayName,emailAddress),storageQuota")
            .execute()
        )
    except Exception as e:
        logger.warning("Drive health check failed: %s", e)
        return {"connected": False, "error": type(e).__name__}

    user = about.get("user", {})
    quota = about.get("storageQuota", {})
    status = {
        "connected": True,
        "account": mask_email(user.get("emailAddress")) or user.get("displayName"),
    }

    try:
        usage = int(quota.get("usage", 0))
        status["usage_human"] = hr_size(usage)
        limit = quota.get("limit")
        if limit:
            limit = int(limit)
            status["limit_human"] = hr_size(limit)
            status["usage_pct"] = round(usage / limit * 100, 1) if limit else None
    except (TypeError, ValueError):
        pass

    return status


@app.route("/health")
def health():
    """Service-level health check (no specific user in scope)."""
    from sgd import db
    try:
        with db.get_conn() as conn:
            conn.execute("SELECT 1")
        db_ok = True
    except Exception as e:
        logger.warning("DB health check failed: %s", e)
        db_ok = False

    resp = jsonify({"status": "ok" if db_ok else "degraded", "db": db_ok})
    resp.status_code = 200 if db_ok else 503
    return resp


@app.route("/u/<user_id>/health")
def user_health(user_id):
    status = drive_status(g.gdrive)
    payload = {
        "status": "ok" if status.get("connected") else "degraded",
        "addon": {
            "id": manifest_for(g.user)["id"],
            "name": manifest_for(g.user)["name"],
            "manifest": manifest_url(user_id),
        },
        "drive": status,
        "config": {"tmdb": _tmdb_pool_has_key()},
    }
    resp = jsonify(payload)
    resp.status_code = 200 if status.get("connected") else 503
    return common_headers(resp)


