@app.route("/u/<user_id>/stream/<stream_type>/<stream_id>.json")
def addon_stream(user_id, stream_type, stream_id):
    invalid_stream_type = stream_type not in BASE_MANIFEST["types"]
    invalid_id = not is_valid_stream_id(stream_id)

    if invalid_stream_type or invalid_id:
        abort(404)

    # Two different one-device-at-a-time mechanisms, and only one of them
    # can work at a time.
    #
    # Through the proxy, the Worker enforces the limit against actual
    # playback (see sgd/proxy_token.py), using a session id issued right
    # here. That is strictly better: it watches bytes rather than menu
    # opens, and its identity is one we minted instead of a User-Agent and
    # an IP - which broke every time an app updated or a phone changed
    # network. So don't also block here; just keep recording the device
    # label for the admin page.
    #
    # Without the proxy there is no Worker in the path and nothing else to
    # enforce anything, so the old fingerprint check still applies.
    session_id = signing.new_session_id()
    proxied = bool(os.environ.get("CF_PROXY_URL")) and _proxy_actually_enabled()

    if proxied:
        _check_device_limit(user_id, request)
    elif not _check_device_limit(user_id, request):
        logger.info("Blocked stream request for user %s - device limit reached", user_id)
        resp = jsonify({
            "streams": [{
                "name": "⚠️ Stream Helium",
                "title": (
                    "Outro dispositivo está usando esta conta. Aguarde até 4 horas "
                    "sem reprodução ou peça ao administrador para liberar o acesso."
                ),
                "externalUrl": admin_whatsapp_link(
                    "Olá! Preciso liberar o dispositivo da minha conta no Stream Helium."
                ),
            }]
        })
        return common_headers(resp)

    # Antes de buscar: se a busca falhar, a pessoa ainda abriu o titulo, e
    # e isso que o catalogo de "voce ainda nao viu" precisa saber.
    _record_view(user_id, stream_id)

    try:
        resp = Response(
            response=get_streams(
                g.gdrive, stream_type, stream_id,
                viewer_id=user_id, session_id=session_id,
            ),
            mimetype="application/json",
        )
        return common_headers(resp)
    except MetadataNotFound as e:
        logger.info("%s", e)
        abort(404)


def _record_view(user_id, stream_id):
    """Marca que esta conta abriu este titulo.

    So o id base: para series, tt1234567:2:5 e o mesmo titulo que
    tt1234567:1:1, e o catalogo raciocina em titulos, nao em episodios.

    Ids tmdb: sao ignorados. O acervo do Catalogo e todo indexado por
    IMDb, entao um id tmdb nunca casaria com nada la — guardar so criaria
    linhas mortas.
    """
    base = split_stream_id(stream_id)[0].lower()
    if not VALID_IMDB_ID.match(base):
        return

    db.record_title_view(user_id, base)


def common_headers(resp_obj):
    resp_obj.headers["Access-Control-Allow-Origin"] = "*"
    resp_obj.headers["Access-Control-Allow-Headers"] = "*"
    resp_obj.headers["X-Robots-Tag"] = "noindex"
    return resp_obj


def get_streams(gdrive, stream_type, stream_id, viewer_id=None, session_id=None):
    # Stream the response body so the connection stays open (and doesn't hit
    # a request timeout) while we search Drive and score the results.
    yield '{"streams":'

    start_time = datetime.now()
    time_taken = lambda st: f"{(datetime.now() - st).total_seconds():.3f}s"

    stream_meta = Meta(stream_type, stream_id)
    gdrive.search(stream_meta)
    logger.info(
        "Got %d/%d unique results from gdrive after deduping in %s. Scoring results...",
        len(gdrive.results), gdrive.len_response, time_taken(start_time),
    )
    streams = Streams(gdrive, stream_meta, viewer_id=viewer_id, session_id=session_id)
    logger.info(
        "Fetched %d/%d valid stream(s) in %s for %s -> %s",
        len(streams.results), len(gdrive.results), time_taken(start_time),
        stream_id, gdrive.query,
    )

    yield f"{dumps(streams.results)}}}"
