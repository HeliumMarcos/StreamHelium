def manifest_for(user_row):
    manifest = dict(BASE_MANIFEST)
    # Distinct addon id per user so multiple accounts can be installed
    # side by side in the same Stremio app without colliding.
    manifest["id"] = f"{BASE_MANIFEST['id']}.{user_row['id']}"
    if user_row.get("display_name"):
        manifest["name"] = f"{BASE_MANIFEST['name']} - {user_row['display_name']}"
    return manifest


def manifest_url(user_id):
    """Vercel terminates TLS in front of the app, so request.url_root comes
    through as http:// - force https so the link we hand to Stremio works."""
    return f"https://{request.host}/u/{user_id}/manifest.json"


